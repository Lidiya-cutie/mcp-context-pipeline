"""DS-748: Methodology for measuring performance of generated code.

Profile and benchmark code snippets generated by LLMs.
Metrics:
- execution_time_ms: wall clock time to run the generated code
- memory_peak_mb: peak memory usage
- cpu_percent: average CPU utilization during execution
- correctness: does the code produce expected output?
- code_size_bytes: size of generated source
- complexity_score: cyclomatic complexity estimate

Approach:
1. Take eval queries that expect code output
2. Generate code using glm-4.7 with expert system prompt
3. Execute in a sandboxed subprocess with resource limits
4. Measure time, memory, CPU
5. Check correctness against expected keywords/structure
"""

from __future__ import annotations

import asyncio
import json
import os
import resource
import statistics
import subprocess
import sys
import tempfile
import textwrap
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import httpx
from dotenv import load_dotenv

_PROJECT_ROOT = Path(os.environ.get(
    "MCP_CONTEXT_PIPELINE_ROOT",
    Path(__file__).resolve().parents[1],
))

load_dotenv(_PROJECT_ROOT / ".env", override=False)

ANTHROPIC_API_KEY = os.environ.get("ANTHROPIC_API_KEY", "")
ANTHROPIC_BASE_URL = os.environ.get("ANTHROPIC_BASE_URL", "https://api.z.ai/api/anthropic")

MAX_EXEC_SECONDS = 10
MAX_MEMORY_MB = 256
TIMEOUT = 60.0

SYSTEM_PROMPT = (
    "You are a code generation system. Generate ONLY executable Python code. "
    "No markdown fences, no explanation. The code must be self-contained "
    "and produce output when run with python3."
)


@dataclass
class CodePerfResult:
    query_id: str
    query: str
    generated_code: str = ""
    code_size_bytes: int = 0
    execution_time_ms: float = 0.0
    memory_peak_kb: int = 0
    correctness: bool = False
    keywords_found: list[str] = field(default_factory=list)
    keywords_missing: list[str] = field(default_factory=list)
    error: str | None = None
    exit_code: int = -1
    output_snippet: str = ""
    complexity_lines: int = 0
    complexity_branches: int = 0


def estimate_complexity(code: str) -> tuple[int, int]:
    lines = [l for l in code.strip().splitlines() if l.strip() and not l.strip().startswith("#")]
    branches = sum(
        1 for l in lines
        if any(kw in l for kw in ("if ", "elif ", "for ", "while ", "except ", "and ", "or "))
    )
    return len(lines), branches


async def generate_code(client: httpx.AsyncClient, query: str) -> str:
    payload = {
        "model": "glm-4.7",
        "max_tokens": 2048,
        "system": SYSTEM_PROMPT,
        "messages": [{"role": "user", "content": query}],
    }
    r = await client.post(
        f"{ANTHROPIC_BASE_URL}/v1/messages",
        json=payload,
        headers={
            "x-api-key": ANTHROPIC_API_KEY,
            "anthropic-version": "2023-06-01",
            "content-type": "application/json",
        },
        timeout=TIMEOUT,
    )
    r.raise_for_status()
    data = r.json()
    text = ""
    for block in data.get("content", []):
        if block.get("type") == "text":
            text += block["text"]
    text = text.strip()
    if text.startswith("```"):
        lines = text.splitlines()
        if lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].startswith("```"):
            lines = lines[:-1]
        text = "\n".join(lines)
    return text


def execute_code(code: str, keywords: list[str]) -> CodePerfResult:
    result = CodePerfResult(query_id="", query="")

    with tempfile.NamedTemporaryFile(mode="w", suffix=".py", delete=False) as f:
        f.write(code)
        f.flush()
        script_path = f.name

    try:
        start = time.monotonic()
        proc = subprocess.run(
            ["python3", script_path],
            capture_output=True,
            text=True,
            timeout=MAX_EXEC_SECONDS,
            env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1"},
        )
        elapsed_ms = (time.monotonic() - start) * 1000
        result.execution_time_ms = round(elapsed_ms, 2)
        result.exit_code = proc.returncode
        result.memory_peak_kb = resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss

        output = (proc.stdout or "") + (proc.stderr or "")
        result.output_snippet = output[:500]

        if proc.returncode != 0:
            result.error = proc.stderr[:500] if proc.stderr else f"exit code {proc.returncode}"
            result.correctness = False
        else:
            result.correctness = True

        lower_output = output.lower()
        result.keywords_found = [k for k in keywords if k.lower() in lower_output]
        result.keywords_missing = [k for k in keywords if k.lower() not in lower_output]
        if keywords:
            result.correctness = len(result.keywords_missing) == 0

    except subprocess.TimeoutExpired:
        result.error = f"Timeout after {MAX_EXEC_SECONDS}s"
        result.execution_time_ms = MAX_EXEC_SECONDS * 1000
    except Exception as exc:
        result.error = str(exc)[:300]
    finally:
        Path(script_path).unlink(missing_ok=True)

    return result


async def main() -> None:
    queries_file = _PROJECT_ROOT / "eval_queries_v3.jsonl"
    queries: list[dict] = []
    with open(queries_file) as f:
        for line in f:
            q = json.loads(line.strip())
            if q.get("expected_answer_type") == "code" or q.get("intent") == "code":
                queries.append(q)
    queries = queries[:8]

    print(f"DS-748: Performance measurement of generated code")
    print(f"Queries with code intent: {len(queries)}")

    results: list[CodePerfResult] = []
    async with httpx.AsyncClient() as client:
        for q in queries:
            keywords = q.get("must_include", [])
            print(f"  Generating code for {q['id']}...", end=" ", flush=True)
            try:
                code = await generate_code(client, q["query"])
                print(f"({len(code)} bytes)")
            except Exception as exc:
                print(f"ERROR: {exc}")
                r = CodePerfResult(
                    query_id=q["id"],
                    query=q["query"],
                    error=f"Generation failed: {str(exc)[:200]}",
                )
                results.append(r)
                continue

            lines, branches = estimate_complexity(code)
            r = execute_code(code, keywords)
            r.query_id = q["id"]
            r.query = q["query"]
            r.generated_code = code[:2000]
            r.code_size_bytes = len(code.encode())
            r.complexity_lines = lines
            r.complexity_branches = branches
            results.append(r)
            print(f"    -> exit={r.exit_code}, time={r.execution_time_ms:.0f}ms, "
                  f"correct={r.correctness}, kw_found={len(r.keywords_found)}/{len(keywords)}")

    correct = sum(1 for r in results if r.correctness)
    executed = sum(1 for r in results if r.exit_code == 0)
    times = [r.execution_time_ms for r in results if r.execution_time_ms > 0 and not r.error]
    mems = [r.memory_peak_kb for r in results if r.memory_peak_kb > 0]
    sizes = [r.code_size_bytes for r in results if r.code_size_bytes > 0]

    summary = {
        "total_queries": len(results),
        "generated_ok": sum(1 for r in results if r.generated_code),
        "executed_ok": executed,
        "correct": correct,
        "correctness_rate": round(correct / max(len(results), 1), 4),
        "execution_rate": round(executed / max(len(results), 1), 4),
        "avg_execution_time_ms": round(statistics.mean(times), 2) if times else 0,
        "stdev_execution_time_ms": round(statistics.stdev(times), 2) if len(times) > 1 else 0,
        "avg_memory_peak_mb": round(statistics.mean(mems) / 1024, 2) if mems else 0,
        "avg_code_size_bytes": round(statistics.mean(sizes), 0) if sizes else 0,
        "avg_complexity_lines": round(statistics.mean([r.complexity_lines for r in results if r.complexity_lines]), 1) if results else 0,
        "avg_complexity_branches": round(statistics.mean([r.complexity_branches for r in results if r.complexity_branches]), 1) if results else 0,
    }

    output = {
        "experiment": "DS-748: Performance measurement of generated code",
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "model": "glm-4.7",
        "system_prompt": SYSTEM_PROMPT[:80] + "...",
        "max_exec_seconds": MAX_EXEC_SECONDS,
        "max_memory_mb": MAX_MEMORY_MB,
        "summary": summary,
        "results": [asdict(r) for r in results],
    }

    outdir = _PROJECT_ROOT / "experiments"
    outdir.mkdir(exist_ok=True)
    outfile = outdir / f"code_performance_benchmark_{int(time.time())}.json"
    with open(outfile, "w") as f:
        json.dump(output, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"\nResults saved to {outfile}")
    print(f"\nSummary:")
    for k, v in summary.items():
        print(f"  {k}: {v}")


if __name__ == "__main__":
    asyncio.run(main())
